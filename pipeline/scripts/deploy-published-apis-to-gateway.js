const https = require("https");

if (String(process.env.APIM_ALLOW_INSECURE_TLS || "").toLowerCase() === "true") {
  process.env.NODE_TLS_REJECT_UNAUTHORIZED = "0";
  console.warn("[deploy-published-apis-to-gateway] WARNING: TLS validation disabled for local demo.");
}

const APIM_HOST = process.env.APIM_HOST || "https://wso2-apim:9443";
const APIM_USERNAME = process.env.APIM_USERNAME || "admin";
const APIM_PASSWORD = process.env.APIM_PASSWORD || "admin";
const GATEWAY_ENV_NAME = process.env.APIM_GATEWAY_ENV_NAME || "Default";
const GATEWAY_VHOST = process.env.APIM_GATEWAY_VHOST || "localhost";

const requestedNames = process.argv.slice(2);
const defaultNames = ["accounts-api", "payments-api", "customers-api", "cards-api", "loans-api"];
const targetNames = requestedNames.length ? requestedNames : defaultNames;

const agent = new https.Agent({ rejectUnauthorized: false });

function basicAuth(user, pass) {
  return Buffer.from(`${user}:${pass}`).toString("base64");
}

async function requestJson(url, options = {}) {
  const isHttps = url.startsWith("https://");
  const lib = isHttps ? https : require("http");

  return new Promise((resolve, reject) => {
    const req = lib.request(url, { ...options, agent: isHttps ? agent : undefined }, (res) => {
      let body = "";
      res.on("data", (chunk) => body += chunk);
      res.on("end", () => {
        const parsed = body ? (() => {
          try { return JSON.parse(body); } catch { return body; }
        })() : {};

        if (res.statusCode >= 400) {
          const err = new Error(`HTTP ${res.statusCode} ${url}: ${body}`);
          err.statusCode = res.statusCode;
          err.body = parsed;
          reject(err);
          return;
        }

        resolve(parsed);
      });
    });

    req.on("error", reject);

    if (options.body) {
      req.write(options.body);
    }

    req.end();
  });
}

async function getPublisherToken() {
  const dcr = await requestJson(`${APIM_HOST}/client-registration/v0.17/register`, {
    method: "POST",
    headers: {
      Authorization: `Basic ${basicAuth(APIM_USERNAME, APIM_PASSWORD)}`,
      "Content-Type": "application/json"
    },
    body: JSON.stringify({
      callbackUrl: "www.google.com",
      clientName: `api-gateway-deployer-${Date.now()}`,
      owner: APIM_USERNAME,
      grantType: "password refresh_token client_credentials",
      saasApp: true
    })
  });

  const params = new URLSearchParams();
  params.set("grant_type", "password");
  params.set("username", APIM_USERNAME);
  params.set("password", APIM_PASSWORD);
  params.set("scope", "apim:api_view apim:api_create apim:api_publish");

  const token = await requestJson(`${APIM_HOST}/oauth2/token`, {
    method: "POST",
    headers: {
      Authorization: `Basic ${basicAuth(dcr.clientId, dcr.clientSecret)}`,
      "Content-Type": "application/x-www-form-urlencoded"
    },
    body: params.toString()
  });

  if (!token.access_token) {
    throw new Error(`Token response did not include access_token: ${JSON.stringify(token)}`);
  }

  return token.access_token;
}

function listOf(payload) {
  return Array.isArray(payload) ? payload : (payload.list || payload.deployments || payload.revisions || []);
}

function revisionIdOf(revision) {
  return revision.id || revision.uuid || revision.revisionUUID || revision.revisionId;
}

async function createOrReuseRevision(token, api) {
  const headers = { Authorization: `Bearer ${token}`, "Content-Type": "application/json" };

  try {
    const created = await requestJson(`${APIM_HOST}/api/am/publisher/v4/apis/${api.id}/revisions`, {
      method: "POST",
      headers,
      body: JSON.stringify({
        description: `Gateway deployment revision for ${api.name} generated by local demo at ${new Date().toISOString()}`
      })
    });

    const id = revisionIdOf(created);

    if (!id) {
      throw new Error(`Revision creation response did not include id: ${JSON.stringify(created)}`);
    }

    console.log(`[deploy-published-apis-to-gateway] created revision for ${api.name}: ${id}`);
    return id;
  } catch (e) {
    console.warn(`[deploy-published-apis-to-gateway] could not create revision for ${api.name}: ${e.message}`);
  }

  const revisions = await requestJson(`${APIM_HOST}/api/am/publisher/v4/apis/${api.id}/revisions`, {
    headers: { Authorization: `Bearer ${token}` }
  });

  const existing = listOf(revisions)
    .map((revision) => ({ revision, id: revisionIdOf(revision) }))
    .filter((item) => item.id)
    .at(-1);

  if (!existing) {
    throw new Error(`No usable revision exists for ${api.name}.`);
  }

  console.log(`[deploy-published-apis-to-gateway] reusing revision for ${api.name}: ${existing.id}`);
  return existing.id;
}

async function deployRevision(token, api, revisionId) {
  const deployments = [
    {
      name: GATEWAY_ENV_NAME,
      vhost: GATEWAY_VHOST,
      displayOnDevportal: true
    }
  ];

  const attempts = [
    {
      method: "POST",
      url: `${APIM_HOST}/api/am/publisher/v4/apis/${api.id}/deployments?revisionId=${encodeURIComponent(revisionId)}`,
      body: deployments
    },
    {
      method: "POST",
      url: `${APIM_HOST}/api/am/publisher/v4/apis/${api.id}/deployments?revisionId=${encodeURIComponent(revisionId)}`,
      body: { deployments }
    },
    {
      method: "POST",
      url: `${APIM_HOST}/api/am/publisher/v4/apis/${api.id}/deploy-revision?revisionId=${encodeURIComponent(revisionId)}`,
      body: deployments
    }
  ];

  let lastError = null;

  for (const attempt of attempts) {
    try {
      await requestJson(attempt.url, {
        method: attempt.method,
        headers: {
          Authorization: `Bearer ${token}`,
          "Content-Type": "application/json"
        },
        body: JSON.stringify(attempt.body)
      });

      console.log(`[deploy-published-apis-to-gateway] deployed ${api.name}:${api.version} revision ${revisionId} to ${GATEWAY_ENV_NAME}/${GATEWAY_VHOST}`);
      return;
    } catch (e) {
      const message = String(e.message || "");
      lastError = e;

      if (message.includes("already") || message.includes("409")) {
        console.log(`[deploy-published-apis-to-gateway] ${api.name}:${api.version} revision already deployed or deployment already exists.`);
        return;
      }
    }
  }

  throw lastError || new Error(`Could not deploy revision ${revisionId} for ${api.name}.`);
}

async function main() {
  console.log(`[deploy-published-apis-to-gateway] APIM_HOST=${APIM_HOST}`);
  console.log(`[deploy-published-apis-to-gateway] Gateway=${GATEWAY_ENV_NAME}/${GATEWAY_VHOST}`);

  const token = await getPublisherToken();

  const apis = await requestJson(`${APIM_HOST}/api/am/publisher/v4/apis?limit=200`, {
    headers: { Authorization: `Bearer ${token}` }
  });

  const available = listOf(apis);
  const targets = available.filter((api) => targetNames.includes(api.name));

  if (!targets.length) {
    throw new Error(`No matching APIs found. Requested: ${targetNames.join(", ")}`);
  }

  for (const api of targets) {
    const detail = await requestJson(`${APIM_HOST}/api/am/publisher/v4/apis/${api.id}`, {
      headers: { Authorization: `Bearer ${token}` }
    });

    if (String(detail.lifeCycleStatus || "").toUpperCase() !== "PUBLISHED") {
      console.warn(`[deploy-published-apis-to-gateway] skipping ${detail.name}:${detail.version}; lifecycle=${detail.lifeCycleStatus}`);
      continue;
    }

    const revisionId = await createOrReuseRevision(token, detail);
    await deployRevision(token, detail, revisionId);
  }

  console.log("[deploy-published-apis-to-gateway] done");
}

main().catch((e) => {
  console.error(`[deploy-published-apis-to-gateway] failed: ${e.message}`);
  process.exit(1);
});
